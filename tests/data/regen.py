"""Regenerate the generated data files in tests/data.

    python tests/data/regen.py            # rewrite files
    python tests/data/regen.py --check    # exit 1 if any file is out of date

Generated files use the independent verifier's arithmetic (tests/verify/_naive.py)
where they hold mathematical values, never the library's.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

from _data import render  # noqa: E402
from verify._naive import primes_upto  # noqa: E402

from corollarykit.registry import BUILTIN_POLICIES, Policy, effective_status, list_bases  # noqa: E402

RETRIEVED = "generated"


def primes_below_100000() -> bytes:
    return render(
        {
            "source": "generated by tests/data/regen.py (verify._naive.primes_upto)",
            "url": "none",
            "retrieved": RETRIEVED,
        },
        [str(p) for p in primes_upto(99_999)],
    )


def snapshot_policies() -> list[Policy]:
    lenient = [
        Policy(
            f"{p.name}+unchecked",
            min_status=p.min_status,
            trusted_proofs=p.trusted_proofs,
            allow_unchecked_transcriptions=True,
        )
        for p in BUILTIN_POLICIES
    ]
    return [*BUILTIN_POLICIES, *lenient]


def policy_snapshot() -> bytes:
    policies = snapshot_policies()
    rows = ["basis\t" + "\t".join(p.name for p in policies)]
    for b in sorted(list_bases(), key=lambda b: b.id):
        cells = []
        for p in policies:
            s = effective_status(b, p)
            cells.append("refused" if s is None else str(s))
        rows.append(b.id + "\t" + "\t".join(cells))
    return render(
        {
            "source": "generated by tests/data/regen.py from the registry",
            "url": "none",
            "retrieved": RETRIEVED,
        },
        rows,
    )


GENERATORS = {
    "primes_below_100000.txt": primes_below_100000,
    "policy_snapshot.txt": policy_snapshot,
}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, gen in GENERATORS.items():
        data = gen()
        path = HERE / name
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(name)
        else:
            path.write_bytes(data)
    if stale:
        print("out of date:", ", ".join(stale), "- run python tests/data/regen.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
